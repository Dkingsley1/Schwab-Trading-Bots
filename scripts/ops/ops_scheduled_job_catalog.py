#!/usr/bin/env python3
from __future__ import annotations

from dataclasses import dataclass

ACTIVE_INSTALL_POLICY = "installed"
REMOVED_INSTALL_POLICY = "removed_legacy"


@dataclass(frozen=True)
class JobSpec:
    job_id: str
    domain: str
    label: str
    runner: str
    artifact: str
    cadence_seconds: int
    freshness_slo_seconds: int
    resource_class: str
    deadline_seconds: int
    owner: str
    authority_boundary: str
    install_policy: str = ACTIVE_INSTALL_POLICY
    dependencies: tuple[str, ...] = ()


def _job(
    job_id: str,
    domain: str,
    runner: str,
    artifact: str,
    *,
    cadence_seconds: int,
    freshness_slo_seconds: int | None = None,
    resource_class: str,
    deadline_seconds: int,
    owner: str,
    authority_boundary: str,
    install_policy: str = ACTIVE_INSTALL_POLICY,
    label_suffix: str | None = None,
    dependencies: tuple[str, ...] = (),
) -> JobSpec:
    return JobSpec(
        job_id=job_id,
        domain=domain,
        label=f"com.dankingsley.ops.{label_suffix or job_id}",
        runner=runner,
        artifact=artifact,
        cadence_seconds=max(int(cadence_seconds), 20 if job_id == "runtime_smooth_mode" else 60),
        freshness_slo_seconds=max(
            int(freshness_slo_seconds or cadence_seconds * 3), 60
        ),
        resource_class=resource_class,
        deadline_seconds=max(int(deadline_seconds), 0),
        owner=owner,
        authority_boundary=authority_boundary,
        install_policy=install_policy,
        dependencies=dependencies,
    )


