secret_placeholder_or_empty() {
  local value="${1:-}"
  case "$value" in
    ""|"YOUR_KEY_HERE"|"YOUR_SECRET_HERE"|"YOUR_REAL_KEY"|"YOUR_REAL_SECRET"|"YOUR_REAL_CLIENT_ID"|"<real_key>"|"<real_secret>"|"<real_client_id>")
      return 0
      ;;
  esac
  return 1
}

read_keychain_secret() {
  local service="$1"
  [[ -n "$service" ]] || return 1
  /usr/bin/security find-generic-password \
    -a "${SCHWAB_KEYCHAIN_ACCOUNT:-${USER:-$(id -un)}}" \
    -s "$service" \
    -w 2>/dev/null || return 1
}

fill_secret_from_keychain() {
  local var_name="$1"
  local service="$2"
  local current="${(P)var_name:-}"
  if ! secret_placeholder_or_empty "$current"; then
    return 0
  fi
  local value
  value="$(read_keychain_secret "$service" || true)"
  if secret_placeholder_or_empty "$value"; then
    return 0
  fi
  export "$var_name=$value"
}

