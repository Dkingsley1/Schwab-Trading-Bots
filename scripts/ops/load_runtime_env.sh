load_file() {
  local f="$1"
  [[ -f "$f" ]] || return 1
  set -a
  # shellcheck disable=SC1090
  source "$f"
  set +a
  return 0
}

local_queue_db_default_path() {
  local local_root="${BOT_CHANNEL_QUEUE_LOCAL_ROOT:-$PROJECT_ROOT/local_fallback_storage}"
  printf '%s\n' "${local_root%/}/data/bot_channel_queue.sqlite3"
}

routed_queue_db_default_path() {
  printf '%s\n' "$PROJECT_ROOT/data/bot_channel_queue.sqlite3"
}

default_queue_db_path() {
  local prefer_local_raw="${BOT_CHANNEL_QUEUE_PREFER_LOCAL:-}"
  if [[ -n "$prefer_local_raw" ]]; then
    case "${prefer_local_raw:l}" in
      1|true|yes|on)
        local_queue_db_default_path
        return 0
        ;;
      *)
        routed_queue_db_default_path
        return 0
        ;;
    esac
  fi

  case "${BOT_LOGS_PREFER_EXTERNAL:-1:l}" in
    0|false|no|off)
      local_queue_db_default_path
      ;;
    *)
      routed_queue_db_default_path
      ;;
  esac
}

